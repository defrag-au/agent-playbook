// Turn `../artifacts/<run-id>/` into the pages and loaders Framework builds.
//
// The artefacts are the source. This script writes under `src/`, so a published
// run is one directory plus a build — never a hand-edited page. It fails the
// build rather than charting a run whose manifest is missing or is a different
// schema.
//
// Generated:
//   src/runs/<id>/index.md      — the claim, then the notebook
//   src/runs/<id>/tables.md     — the generated tables
//   src/data/<id>-traces.json.js
//   src/data/<id>-tools.json.js
//   src/data/<id>-checks.json.js
//
// `src/data/runs.json.js` is static: it scans the artefacts for the index pages.

import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const SCHEMA = 1;
const SITE = fileURLToPath(new URL("../..", import.meta.url));
const ARTIFACTS = join(SITE, "artifacts");
const SRC = join(SITE, "frontend", "src");
const RUNS = join(SRC, "runs");
const DATA = join(SRC, "data");

const REQUIRED = [
  "manifest.json",
  "summary.md",
  "traces.json",
  "tools.json",
  "checks.json",
  "observable.md",
];

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function runs() {
  if (!existsSync(ARTIFACTS)) return [];
  return readdirSync(ARTIFACTS, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .map((id) => ({ id, dir: join(ARTIFACTS, id) }))
    .filter(({ dir }) => existsSync(join(dir, "manifest.json")))
    .map(({ id, dir }) => ({ id, dir, manifest: readJson(join(dir, "manifest.json")) }))
    .sort((a, b) => b.manifest.started_ms - a.manifest.started_ms);
}

function validate({ id, dir, manifest }) {
  if (manifest.schema_version !== SCHEMA) {
    throw new Error(
      `${id}: manifest schema_version ${manifest.schema_version}, this site reads ${SCHEMA}. ` +
        "Regenerate the run; do not chart it as-is.",
    );
  }
  for (const name of REQUIRED) {
    if (!existsSync(join(dir, name))) {
      throw new Error(`${id}: missing ${name}`);
    }
  }
}

function label(manifest) {
  const date = new Date(manifest.started_ms).toISOString().slice(0, 10);
  return `${date} · ${manifest.model}`;
}

// The run page supplies its own H1, and the streams are not published beside the
// summary on the site, so drop the two lines that are only true in a run directory.
function withoutTitle(text) {
  const lines = text.split("\n");
  if (lines[0]?.startsWith("# ")) {
    lines.shift();
    while (lines[0] === "") lines.shift();
  }
  return lines;
}

function summaryForSite(summary) {
  const kept = withoutTitle(summary).filter(
    (line) => !line.startsWith("Streams, stderr and effect logs are beside this file"),
  );
  while (kept.at(-1) === "") kept.pop();
  return kept.join("\n");
}

function notebookForSite(notebook, id) {
  return withoutTitle(notebook)
    .join("\n")
    .replaceAll('FileAttachment("traces.json")', `FileAttachment("../../data/${id}-traces.json")`)
    .replaceAll('FileAttachment("tools.json")', `FileAttachment("../../data/${id}-tools.json")`)
    .replaceAll('FileAttachment("checks.json")', `FileAttachment("../../data/${id}-checks.json")`);
}

function loader(id, kind) {
  return `// Generated by scripts/sync-runs.mjs — do not edit.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const manifest = JSON.parse(
  readFileSync(
    fileURLToPath(new URL("../../../artifacts/${id}/manifest.json", import.meta.url)),
    "utf8",
  ),
);
if (manifest.schema_version !== ${SCHEMA}) {
  throw new Error(
    \`${id}: manifest schema_version \${manifest.schema_version}, this loader reads ${SCHEMA}\`,
  );
}
process.stdout.write(
  readFileSync(
    fileURLToPath(new URL("../../../artifacts/${id}/${kind}.json", import.meta.url)),
    "utf8",
  ),
);
`;
}

function writeRun({ id, dir, manifest }) {
  const page = join(RUNS, id);
  mkdirSync(page, { recursive: true });

  const claimFile = join(dir, "claim.md");
  const claim = existsSync(claimFile)
    ? readFileSync(claimFile, "utf8").trim()
    : [
        "> **No authored claim yet.** The tables below are generated from the run",
        "> artefact: they describe what happened, not what it means.",
      ].join("\n");

  const summary = summaryForSite(readFileSync(join(dir, "summary.md"), "utf8"));
  const notebook = notebookForSite(readFileSync(join(dir, "observable.md"), "utf8"), id);
  for (const kind of ["traces", "tools", "checks"]) {
    if (!notebook.includes(`../../data/${id}-${kind}.json`)) {
      throw new Error(
        `${id}: notebook does not reference ${kind}.json; the export template changed and the ` +
          "rewrite no longer matches",
      );
    }
  }

  writeFileSync(
    join(page, "index.md"),
    `# ${label(manifest)}\n\n${claim}\n\n---\n\n${notebook}\n`,
  );
  writeFileSync(join(page, "tables.md"), `# Tables — ${label(manifest)}\n\n${summary}\n`);

  for (const kind of ["traces", "tools", "checks"]) {
    writeFileSync(join(DATA, `${id}-${kind}.json.js`), loader(id, kind));
  }
}

mkdirSync(RUNS, { recursive: true });
for (const entry of readdirSync(RUNS, { withFileTypes: true })) {
  if (entry.isDirectory()) {
    rmSync(join(RUNS, entry.name), { recursive: true, force: true });
  }
}
for (const name of readdirSync(DATA)) {
  if (/-(traces|tools|checks)\.json\.js$/.test(name)) {
    rmSync(join(DATA, name));
  }
}

const published = runs();
for (const run of published) validate(run);
for (const run of published) writeRun(run);

console.log(`synced ${published.length} run(s) from ${ARTIFACTS}`);
